package com.example.data.network

import java.net.URI
import java.net.URLDecoder
import java.util.UUID

/** Ephemeral secret; never persist or use its default data-class/string representation. */
class PairingBootstrap internal constructor(
    val host: String, val port: Int, val fingerprint: String,
    val id: String, val token: String, val expires: Long
) {
    override fun toString() = "PairingBootstrap(version=2; secret omitted)"
    fun requireUnexpired(now: Long = System.currentTimeMillis()) {
        if (expires <= now) throw GatewayException("PAIR_EXPIRED", message = "The pairing code expired. Generate a new code on the PC.")
    }
}

object PairingBootstrapParser {
    private val uuid = Regex("[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}")
    internal fun deviceId(value: String): Boolean = uuid.matches(value) && runCatching { UUID.fromString(value).toString() == value }.getOrDefault(false)
    fun isBootstrap(text: String): Boolean = runCatching { URI(text.trim()).rawPath == "/v2" }.getOrDefault(false)
    fun parse(text: String, now: Long = System.currentTimeMillis()): PairingBootstrap {
        try {
            require(text.length in 1..2048 && text == text.trim())
            val uri = URI(text)
            require(uri.scheme == "privateai" && uri.host == "pair" && uri.rawAuthority == "pair" && uri.rawPath == "/v2" && uri.fragment == null && uri.userInfo == null)
            val values = linkedMapOf<String, String>()
            uri.rawQuery.orEmpty().split("&").forEach { field ->
                val parts = field.split("=", limit = 2)
                require(parts.size == 2)
                val key = URLDecoder.decode(parts[0], "UTF-8")
                require(!values.containsKey(key))
                values[key] = URLDecoder.decode(parts[1], "UTF-8")
            }
            require(values.keys == setOf("version", "host", "port", "fingerprint", "id", "token", "expires"))
            if (values["version"] != "2") throw GatewayException("PAIR_VERSION", message = "This pairing version is unsupported. Update the companion and generate a compatible code on the PC.")
            val host = values.getValue("host")
            require(PairingConfigParser.privateAddress(host))
            val rawPort = values.getValue("port")
            require(Regex("[1-9][0-9]{0,4}").matches(rawPort))
            val port = rawPort.toInt()
            require(port in 1..65535)
            val fingerprint = values.getValue("fingerprint")
            require(Regex("[a-f0-9]{64}").matches(fingerprint) && deviceId(values.getValue("id")))
            val token = values.getValue("token")
            require(Regex("[A-Za-z0-9_-]{43}").matches(token))
            val rawExpires = values.getValue("expires")
            require(Regex("[1-9][0-9]{0,18}").matches(rawExpires))
            val expires = rawExpires.toLong()
            val result = PairingBootstrap(host, port, fingerprint, values.getValue("id"), token, expires)
            result.requireUnexpired(now)
            require(expires - now in 1..300_000L)
            return result
        } catch (e: GatewayException) { throw e }
        catch (_: Exception) { throw GatewayException("PAIR_CODE", message = "Use the complete, current secure pairing code generated by Private AI on your PC.") }
    }
}
